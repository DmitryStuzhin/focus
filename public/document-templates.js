export function templatePrompt(id){
 const template=documentTemplates.find(entry=>entry.id===id);
 if(!template)return null;
 return template.prompt+' Отмечайте отсутствующие сведения как «уточнить». Сохраните структуру, пригодную для экспорта в DOCX.';
}
